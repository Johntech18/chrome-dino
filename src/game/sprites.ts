/* ----------------------------------------------------------- PTERODACTYL */
/* 28 x 23. Faces left. The head/body band is identical in every frame, only
   the wings move, so flapping never nudges the hitbox.                       */

const PT_W = 28;
const PT_H = 23;

/** Solid body band that the hitbox is built from (rows 9..13). */
export const PTERO_BODY_TOP = 9;
export const PTERO_BODY_ROWS = 5;

const PT_BODY: { row: number; text: string }[] = [
  { row: 8, text: "........####................" },
  { row: 9, text: "#########.####.............." },
  { row: 10, text: ".#######.#####################" },
  { row: 11, text: ".......#######################" },
  { row: 12, text: "..........################..." },
  { row: 13, text: "............##########......" },
];

function ptero(wing: "up" | "mid" | "down"): PixelMap {
  const grid: boolean[][] = Array.from({ length: PT_H }, () => Array(PT_W).fill(false));
  const paint = (row: number, from: number, to: number) => {
    for (let c = from; c <= to && c < PT_W; c++) if (c >= 0) grid[row][c] = true;
  };

  for (const b of PT_BODY) {
    for (let c = 0; c < b.text.length && c < PT_W; c++) if (b.text[c] === "#") grid[b.row][c] = true;
  }

  const R = 26;
  if (wing === "up") {
    for (let i = 0; i <= 10; i++) paint(i, 25 - Math.round(i * 1.2), R);
    // feather notches along the trailing edge
    grid[3][R] = false;
    grid[6][R] = false;
  } else if (wing === "down") {
    for (let j = 0; j <= 10; j++) paint(12 + j, 13 + Math.round(j * 1.2), R);
    grid[19][R] = false;
    grid[16][R] = false;
  } else {
    for (let i = 5; i <= 10; i++) paint(i, 22 - Math.round((i - 5) * 1.8), R);
    for (let j = 0; j <= 5; j++) paint(12 + j, 13 + Math.round(j * 1.8), R);
  }

  return build(grid.map((r) => r.map((v) => (v ? "#" : ".")).join("")));
}

