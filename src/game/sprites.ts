/**
 * Hand-authored pixel maps.
 *   '#' = primary colour
 *   '+' = accent colour (optional second ink)
 *   '.' = transparent
 * Every sprite is normalised to a rectangle and cached as an offscreen canvas
 * per (colour, accent, scale).
 */

export type PixelMap = {
  w: number;
  h: number;
  rows: string[];
};

function build(rows: string[]): PixelMap {
  const w = Math.max(...rows.map((r) => r.length));
  return { w, h: rows.length, rows: rows.map((r) => r.padEnd(w, ".")) };
}

