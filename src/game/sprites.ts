/* ------------------------------------------------------------------ CACHE */

const cache = new WeakMap<PixelMap, Map<string, HTMLCanvasElement>>();

/** Rasterise a pixel map into a cached offscreen canvas. */
export function raster(
  map: PixelMap,
  color: string,
  scale: number,
  accent: string = color,
): HTMLCanvasElement {
  let bucket = cache.get(map);
  if (!bucket) {
    bucket = new Map();
    cache.set(map, bucket);
  }
  const key = `${color}|${accent}|${scale}`;
  const cached = bucket.get(key);
  if (cached) return cached;

  const cv = document.createElement("canvas");
  cv.width = map.w * scale;
  cv.height = map.h * scale;
  const ctx = cv.getContext("2d")!;
  for (let y = 0; y < map.h; y++) {
    const row = map.rows[y];
    for (let x = 0; x < map.w; x++) {
      const ch = row[x];
      if (ch === "#" || ch === "+") {
        ctx.fillStyle = ch === "#" ? color : accent;
        let run = 1;
        while (x + run < map.w && row[x + run] === ch) run++;
        ctx.fillRect(x * scale, y * scale, run * scale, scale);
        x += run - 1;
      }
    }
  }
  bucket.set(key, cv);
  return cv;
}

